using Microsoft.EntityFrameworkCore;
namespace Comedores.Web;
public class AuditLog {
 public long Id{get;set;}
 public DateTime OccurredAt{get;set;}=DateTime.UtcNow;
 public string Actor{get;set;}="";
 public string Ip{get;set;}="";
 public string Action{get;set;}="";
 public string Target{get;set;}="";
 public string Detail{get;set;}="";
 public string Origin{get;set;}="Aplicación";
 public string? SourceKey{get;set;}
 public static AuditLog Request(HttpContext context,string action,string target,string detail="")=>new(){Actor=context.User.Identity?.Name??"Anónimo",Ip=context.Connection.RemoteIpAddress?.ToString()??"",Action=action,Target=target,Detail=detail};
 public static async Task EnsureSchemaAsync(AppDb db){
  await db.Database.ExecuteSqlRawAsync("""
 CREATE TABLE IF NOT EXISTS "AuditLogs" (
 "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"OccurredAt" timestamp with time zone NOT NULL,
 "Actor" text NOT NULL,"Ip" text NOT NULL,"Action" text NOT NULL,"Target" text NOT NULL,"Detail" text NOT NULL,"Origin" text NOT NULL,"SourceKey" text NULL);
 CREATE UNIQUE INDEX IF NOT EXISTS "IX_AuditLogs_SourceKey" ON "AuditLogs"("SourceKey");
 CREATE INDEX IF NOT EXISTS "IX_AuditLogs_OccurredAt_Id" ON "AuditLogs"("OccurredAt","Id");
 CREATE INDEX IF NOT EXISTS "IX_AuditLogs_Actor_OccurredAt" ON "AuditLogs"("Actor","OccurredAt");
 INSERT INTO "AuditLogs"("OccurredAt","Actor","Ip","Action","Target","Detail","Origin","SourceKey")
 SELECT c."OccurredAt",c."Operator",c."Ip",'Registro de servicio','Consumo #'||c."Id",'Empleado '||e."Number"||' · '||r."Name"||' · '||c."Type",'Histórico','consumption:'||c."Id"||':registro'
 FROM "Consumptions" c JOIN "Employees" e ON e."Id"=c."EmployeeId" JOIN "DiningRooms" r ON r."Id"=c."DiningRoomId"
 ON CONFLICT("SourceKey") DO NOTHING;
 INSERT INTO "AuditLogs"("OccurredAt","Actor","Ip","Action","Target","Detail","Origin","SourceKey")
 SELECT "OccurredAt","Actor",'',"Action","Account","Reason",'Histórico','security:'||"Id" FROM "AccountSecurityEvents"
 ON CONFLICT("SourceKey") DO NOTHING;
 """);
 }
}
